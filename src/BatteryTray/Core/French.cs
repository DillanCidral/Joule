/// <summary>
/// French translation. The rest of the code keeps its Portuguese/English pairs
/// untouched: here the English text is the key. A text missing from the table
/// stays in English, so a new string never breaks anything: just add its line.
/// Exact = fixed texts; Patterns = texts with a value inside.
/// </summary>
public static class French
{
    private static readonly ConcurrentDictionary<string, string> Cache = new(StringComparer.Ordinal);

    public static string Of(string en)
    {
        if (Exact.TryGetValue(en, out var fr)) return fr;
        return Cache.GetOrAdd(en, static key =>
        {
            foreach (var (pattern, replacement) in Patterns)
            {
                var m = pattern.Match(key);
                if (m.Success) return m.Result(replacement);
            }
            return key;
        });
    }

    private static (Regex, string) P(string pattern, string replacement) =>
        (new Regex(pattern, RegexOptions.CultureInvariant | RegexOptions.Singleline), replacement);

