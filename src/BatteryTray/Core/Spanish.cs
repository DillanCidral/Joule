    private static readonly ConcurrentDictionary<string, string> Cache = new(StringComparer.Ordinal);

    public static string Of(string en)
    {
        if (Exact.TryGetValue(en, out var es)) return es;
        return Cache.GetOrAdd(en, static key =>
        {
            foreach (var (pattern, replacement) in Patterns)
            {
                var m = pattern.Match(key);
                if (m.Success) return m.Result(replacement);
            }
            return key;
        });
    }

    private static (Regex, string) P(string pattern, string replacement) =>
