//! The udev rule that lets the logged-in user open the hidraw nodes of the devices Joule knows
//! (`TAG+="uaccess"`). The checked-in `packaging/99-joule.rules` must equal [`rules`]; `joule --udev-rules`
//! prints it.

use crate::{logitech_headset, logitech_receiver};

/// Every VID:PID a provider claims, as (vendor, product), sorted and unique.
pub fn known_ids() -> Vec<(u16, u16)> {
    let mut ids: Vec<(u16, u16)> = logitech_headset::known_pids()
        .into_iter()
        .map(|p| (0x046D, p))
        .collect();
    ids.extend(
        logitech_receiver::RECEIVERS
            .iter()
            .map(|(p, _)| (0x046D, *p)),
    );
    ids.sort_unstable();
    ids.dedup();
    ids
}

pub fn rules() -> String {
    let mut out = String::from(
        "# Joule: let the logged-in user read the battery of these devices (hidraw nodes).\n\
         # Generated by `joule --udev-rules`; do not edit by hand.\n",
    );
    for (vid, pid) in known_ids() {
        out.push_str(&format!(
            "KERNEL==\"hidraw*\", SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{vid:04x}\", ATTRS{{idProduct}}==\"{pid:04x}\", TAG+=\"uaccess\"\n"
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_checked_in_rule_is_the_generated_one() {
        let file = include_str!("../../../packaging/99-joule.rules");
        assert_eq!(
            file,
            rules(),
            "regenerate with: joule --udev-rules > linux/packaging/99-joule.rules"
        );
    }
    #[test]
    fn it_covers_the_g933_and_the_lightspeed_receiver() {
        let r = rules();
        assert!(r.contains("\"0a5b\""), "G933 dongle");
        assert!(r.contains("\"c539\""), "Lightspeed receiver");
        assert!(
            r.lines()
                .filter(|l| l.starts_with("KERNEL"))
                .all(|l| l.contains("TAG+=\"uaccess\""))
        );
    }
    #[test]
    fn ids_are_unique() {
        let ids = known_ids();
        let mut u = ids.clone();
        u.dedup();
        assert_eq!(ids, u);
    }
}
